// Generates supabase/seed.sql from the sample tournament (same data as the static branch),
// plus test logins: every sample player gets <ign>@example.com, and two staff accounts.
// Usage: npm run seed-sql   (then `npx supabase db reset` to apply)

import { writeFileSync } from "node:fs";
import { GROUP_DAY_MODES } from "../src/content/event.ts";
import { parseTournament } from "../src/lib/parse.ts";
import { SAMPLE_TABS } from "../src/lib/sample-data.ts";

const { raw } = parseTournament(SAMPLE_TABS);
const q = (v: string | number | boolean | undefined | null) =>
  v === undefined || v === null || v === "" ? "null" : typeof v === "string" ? `'${v.replace(/'/g, "''")}'` : String(v);
const emailFor = (ign: string) => `${ign.toLowerCase().replace(/[^a-z0-9]+/g, ".")}@example.com`;

const out: string[] = ["-- Generated by scripts/seed-sql.ts — do not edit by hand.", ""];

out.push("insert into staff (email, role) values ('admin@example.com', 'admin'), ('ref@example.com', 'referee');", "");

for (const t of raw.teams) {
  out.push(`insert into teams (id, name, tag, group_name, logo_url) values (${q(t.id)}, ${q(t.name)}, ${q(t.tag)}, ${q(t.group)}, ${q(t.logoUrl)});`);
  t.players.forEach((p, i) => {
    out.push(
      `with p as (insert into players (team_id, ign, codm_uid, role, is_captain) values (${q(t.id)}, ${q(p.ign)}, ${q(p.codmUid)}, ${q(p.role)}, ${t.captain === p.ign}) returning id)` +
        ` insert into player_contacts (player_id, email, phone, age) select id, ${q(emailFor(p.ign))}, ${q(`98${String(1e8 + i).slice(1)}`)}, 20 from p;`,
    );
  });
}
out.push("");

for (const m of raw.matches) {
  out.push(
    `insert into matches (id, stage, group_name, round, best_of, side_a, side_b, scheduled_at) values (${q(m.id)}, ${q(m.stage)}, ${q(m.group)}, ${q(m.round)}, ${m.bestOf}, ${q(m.sideA)}, ${q(m.sideB)}, ${q(m.scheduledAt)});`,
  );
  for (const g of m.maps) {
    // Backdate so seeded results don't open a fresh 10-minute dispute window.
    const ended = m.scheduledAt ? `(${q(m.scheduledAt)}::timestamptz + interval '25 minutes')` : "now() - interval '1 day'";
    out.push(`insert into maps (match_id, game, mode, map, score_a, score_b, status, updated_at) values (${q(m.id)}, ${g.game}, ${q(g.mode)}, ${q(g.map)}, ${g.scoreA}, ${g.scoreB}, 'final', ${ended});`);
  }
}
out.push("");

const cfg: [string, string | number | undefined][] = [
  ["qualifiers_per_group", raw.config.qualifiersPerGroup],
  ["tiebreakers", raw.config.tiebreakers.join(", ")],
  ["perspective", raw.config.perspective],
  ["event_dates", raw.config.eventDates],
];
for (const [k, v] of cfg) out.push(`insert into config (key, value) values (${q(k)}, ${q(String(v ?? ""))});`);
for (const a of raw.announcements) out.push(`insert into announcements (date, title, body) values (${q(a.date)}, ${q(a.title)}, ${q(a.body)});`);
for (const m of raw.mapPool) out.push(`insert into map_pool (mode, map) values (${q(m.mode)}, ${q(m.map)});`);

// Mode of the day for all five group evenings, as published on 15 Nov.
for (const d of GROUP_DAY_MODES) out.push(`insert into match_days (day, mode) values (${q(d.day)}, ${q(d.mode)});`);

writeFileSync("supabase/seed.sql", out.join("\n") + "\n");
console.log(`supabase/seed.sql: ${raw.teams.length} teams, ${raw.matches.length} matches`);
